"""DD-A73: a training run created from a generated / search candidate whose YAML carries ETRI mixed blocks
(NASGlobalTransformer / NASWindowTransformer / NASPatchMerge) binds its structure in a core process that never ran an
explicit structure check before (T5 rerun2 ``genconfig-create`` 02:30:50Z was rejected 422 STRUCTURE_INVALID /
BLOCK_UNSUPPORTED ``KeyError: 'NASGlobalTransformer'`` because ``training_runs.selection.bind_structure`` built the model
without registering the mixed blocks; it passed only after an explicit candidate check had loaded them in the process).

* the fix path runs in a FRESH interpreter (``python -I -B``: nothing registered before, asserted) on the exact YAML of
  the T5 candidate ``RAND:s7:g00:c000`` (generated by ``examples/protocol.cpu_generation_only.json``): PASS, the
  structure, hashes and the resolved training arch are recorded and the blocks are registered afterwards;
* the backend-unavailable branch records UNVERIFIED / STRUCTURE_RUNTIME_UNAVAILABLE, never raises and builds nothing;
* a candidate without mixed blocks never touches the mixed backend.

The negative control (``load_etri_mixed`` replaced by a no-op = the pre-DD-A73 behaviour -> the T5 KeyError) is kept as
evidence (docs/internal/evidence/WP7/FIX6_DD_A73/negative_control/), not as a test. CPU only; tiny 64 px builds."""
