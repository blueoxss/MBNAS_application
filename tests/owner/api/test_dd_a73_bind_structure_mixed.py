def _source(text: str, family: str) -> tuple[dict, dict]:
    genotype = Genotype.from_yaml_text(text, family=family, template_id="cand")
    arch = {"model_id": "cand", "family": "YOLO11", "backend": "ultralytics", "variant": "detect", "config": genotype.yaml,
            "register_hook": "mbnas_model_runtime.operators:ensure_registered" if yaml_uses_mixed_modules(genotype.yaml)
            else None}
    source = {"kind": "generated", "run_id": "run-x", "candidate_id": "cand", "name": "cand", "family": family,
              "architecture_yaml": genotype.yaml_text(), "architecture_hash": None, "yaml_hash": genotype.yaml_hash(),
              "blocks": [], "genotype": genotype.to_json(), "dataset_class_count": 1, "arch": arch}
    resolved = {"console": {"paths": {}, "extra": {"training": {"arch": arch}}},
                "training": {"requested_input_size": [64, 64]}}
    return source, resolved


def test_fresh_interpreter_binds_a_generated_mixed_candidate_without_a_prior_check(tmp_path):
    yaml_path = tmp_path / "t5_c000.yaml"
    yaml_path.write_text(T5_C000_YAML, encoding="utf-8")
    probe = tmp_path / "probe.py"
    probe.write_text(PROBE, encoding="utf-8")
    env = {k: v for k, v in os.environ.items() if not k.startswith("PYTHON")}
    env.update(CUDA_VISIBLE_DEVICES="", PYTHONDONTWRITEBYTECODE="1", HF_HUB_OFFLINE="1", YOLO_OFFLINE="1",
               YOLO_CONFIG_DIR=str(tmp_path / "ultralytics_cfg"))
    p = subprocess.run([sys.executable, "-I", "-B", str(probe), str(yaml_path)], env=env, cwd=str(tmp_path),
                       capture_output=True, text=True, timeout=600)
    lines = [line for line in p.stdout.splitlines() if line.startswith("RESULT ")]
    assert p.returncode == 0 and lines, (p.returncode, p.stdout[-2000:], p.stderr[-4000:])
    out = json.loads(lines[-1][len("RESULT "):])
    assert out["sys_flags_isolated"] is True and out["registered_before"] is False  # a fresh process, nothing loaded
    assert out["raised"] is None, out
    assert out["status"] == "PASS", out["diagnostics"]
    assert not any("KeyError" in str(d.get("cause")) for d in out["diagnostics"])
    assert "NASGlobalTransformer" in out["modules"] and len(out["modules"]) == 24
    assert out["architecture_hash"] and out["architecture_hash"] == out["resolved_arch_hash"]
    assert out["resolved_arch_hook"] == "mbnas_model_runtime.operators:ensure_registered"
    assert out["registered_after"] is True  # bind_structure registered the mixed blocks in this process (DD-A73)


def test_mixed_backend_unavailable_records_unverified_and_never_builds(monkeypatch):
    import mbnas_core.search.mixed_pool.bridge as bridge
    import mbnas_core.search.structure as structure

    def unavailable(*a, **k):
        raise bridge.EtriUnavailable("SYNTHETIC: mixed-block backend missing on this core host")

    def no_build(*a, **k):
        raise AssertionError("no model may be built when the mixed backend is unavailable")

    monkeypatch.setattr(bridge, "load_etri_mixed", unavailable)
    monkeypatch.setattr(structure, "check_structure", no_build)
    source, resolved = _source(T5_C000_YAML, "NAS:hybrid_backbone")
    bind_structure(source, resolved, "scratch")  # does not raise
    st = source["structure"]
    assert st["status"] == "UNVERIFIED" and st["blocks"] == [] and st["edges"] == []
    (diag,) = st["diagnostics"]
    assert diag["code"] == "STRUCTURE_RUNTIME_UNAVAILABLE" and "EtriUnavailable" in diag["cause"]
    assert source["architecture_yaml"] and source["yaml_hash"] and source["genotype"]
    assert resolved["console"]["extra"]["training"]["arch"]["register_hook"]  # the runner still registers the blocks


def test_candidate_without_mixed_blocks_never_touches_the_mixed_backend(monkeypatch):
    import mbnas_core.search.mixed_pool.bridge as bridge

    def must_not_load(*a, **k):
        raise AssertionError("load_etri_mixed called for a candidate without mixed blocks")

    monkeypatch.setattr(bridge, "load_etri_mixed", must_not_load)
    source, resolved = _source(CNN_YAML, "NAS:cnn_backbone")
    bind_structure(source, resolved, "scratch")
    assert source["structure"]["status"] == "PASS", source["structure"]["diagnostics"]
    assert source["architecture_hash"] == resolved["console"]["extra"]["training"]["architecture_hash"]
