"""Deterministic PILOT_SMOKE subset writer (real images copied, disjoint roles, source dataset untouched).

Source layout: ``images/{train,val,test}`` + ``labels/{train,val,test}``. Roles: ``train``←train, ``search_val``←val,
``final_eval``←test. Output: ``images/<role>``, ``labels/<role>``, ``data.yaml``, ``manifest.json`` (written last; its
presence makes a second call a no-op).
"""
from __future__ import annotations

import json
import os
import random
import shutil
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path
from typing import Any

from mbnas_contracts.util.atomic import atomic_write_bytes, atomic_write_json, sha256_file
from mbnas_model_runtime.datasets.manifest import IMAGE_EXTS

SUBSET_SCHEMA = "mbnas.pilot_subset/1"
ROLE_SOURCES = (("train", "train"), ("search_val", "val"), ("final_eval", "test"))
SELECTION_RULE = "per role: sorted(source image file names); random.Random(seed).sample(names, n); files copied"


class SubsetError(RuntimeError):
    """The subset cannot be built (source layout missing or not enough images)."""


@dataclass(frozen=True)
class SubsetSpec:
    """What to build: ``n_*`` images per role from ``source`` into ``out``; ``names`` are the class names."""

    source: Path
    out: Path
    seed: int = 2026
    n_train: int = 32
    n_search_val: int = 16
    n_final_eval: int = 16
    names: tuple[str, ...] = ("0",)

    def count(self, role: str) -> int:
        return {"train": self.n_train, "search_val": self.n_search_val, "final_eval": self.n_final_eval}[role]


def _label_rows(path: Path) -> int:
    return sum(1 for line in path.read_text(encoding="utf-8", errors="replace").splitlines() if line.strip())


def build_subset(spec: SubsetSpec, log: Callable[[str], None] = print) -> dict[str, Any] | None:
    """Build the subset and return its manifest dict, or None when ``out/manifest.json`` already exists (``[skip]``).

    The last log line is ``data.yaml: <path>``; too few source images raise :class:`SubsetError` ("not enough images").
    """
    source, out = Path(spec.source), Path(os.path.abspath(spec.out))
    if (out / "manifest.json").is_file() and (out / "data.yaml").is_file():
        log(f"[skip] {out} already holds a subset (manifest.json present)")
        return None
    plan: dict[str, tuple[str, list[str]]] = {}
    for role, src_split in ROLE_SOURCES:
        img_dir = source / "images" / src_split
        if not img_dir.is_dir():
            raise SubsetError(f"source split directory missing: {img_dir}")
        names = sorted(p.name for p in img_dir.iterdir() if p.is_file() and p.suffix.lower() in IMAGE_EXTS)
        want = spec.count(role)
        if len(names) < want:
            raise SubsetError(f"not enough images in {img_dir}: need {want}, found {len(names)}")
        plan[role] = (src_split, sorted(random.Random(spec.seed).sample(names, want)))
    roles: dict[str, Any] = {}
    for role, (src_split, picked) in plan.items():
        (out / "images" / role).mkdir(parents=True, exist_ok=True)
        (out / "labels" / role).mkdir(parents=True, exist_ok=True)
        samples = []
        for name in picked:
            src_img, stem = source / "images" / src_split / name, Path(name).stem
            src_lbl = source / "labels" / src_split / f"{stem}.txt"
            shutil.copyfile(src_img, out / "images" / role / name)
            label_sha, rows = None, 0
            if src_lbl.is_file():
                shutil.copyfile(src_lbl, out / "labels" / role / f"{stem}.txt")
                label_sha, rows = sha256_file(src_lbl), _label_rows(src_lbl)
            samples.append({"sample_id": stem, "file": name, "image_sha256": sha256_file(src_img),
                            "label_sha256": label_sha, "boxes": rows})
        roles[role] = {"source_split": src_split, "count": len(samples), "samples": samples}
        log(f"[ok] {role}: {len(samples)} images from {src_split}")
    yaml_lines = ["# generated by mbnas_server.datasets.subset (PILOT_SMOKE subset)", f"path: {json.dumps(str(out))}",
                  "train: images/train", "val: images/search_val", "test: images/final_eval", "names:",
                  *(f"  {i}: {json.dumps(n)}" for i, n in enumerate(spec.names))]
    atomic_write_bytes(out / "data.yaml", ("\n".join(yaml_lines) + "\n").encode("utf-8"))
    manifest = {"schema": SUBSET_SCHEMA, "seed": spec.seed, "source": str(source), "selection_rule": SELECTION_RULE,
                "class_ids": list(range(len(spec.names))), "names": list(spec.names), "roles": roles}
    atomic_write_json(out / "manifest.json", manifest)
    log(f"data.yaml: {out / 'data.yaml'}")
    return manifest
